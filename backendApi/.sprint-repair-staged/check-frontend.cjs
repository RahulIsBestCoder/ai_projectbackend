const ts = require('../../frontendai/node_modules/typescript');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve('../frontendai');
const config = ts.readConfigFile(path.join(root, 'tsconfig.json'), ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const host = ts.createCompilerHost(parsed.options);
const originalRead = host.readFile;
const target = path.join(root, 'src/app/pages/csr-pages/PlansView.tsx').toLowerCase();
host.readFile = file => path.resolve(file).toLowerCase() === target ? fs.readFileSync('.sprint-repair-staged/PlansView.tsx', 'utf8') : originalRead(file);
const program = ts.createProgram(parsed.fileNames, parsed.options, host);
const diagnostics = ts.getPreEmitDiagnostics(program);
const changed = diagnostics.filter(d => d.file && path.resolve(d.file.fileName).toLowerCase() === target);
console.log(`Frontend diagnostics: ${diagnostics.length} total; ${changed.length} in changed PlansView.tsx`);
console.log(ts.formatDiagnosticsWithColorAndContext(changed, { getCurrentDirectory:()=>root, getCanonicalFileName:f=>f, getNewLine:()=> '\n' }));
process.exitCode = changed.length ? 1 : 0;
