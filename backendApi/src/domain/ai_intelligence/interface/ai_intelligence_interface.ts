/**
 * Compact, stored project context. Assembled from project/analytics/risk data,
 * real sprints + work items, and accepted plan-execution progress, then
 * summarized by the AI provider (deterministic fallback) and hard-capped to
 * PROJECT_CONTEXT_MAX_LINES / PROJECT_CONTEXT_MAX_CHARS. Persisted on
 * `projects.project_context` and consumed by the AI chat.
 */
