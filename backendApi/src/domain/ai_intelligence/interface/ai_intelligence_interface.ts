/**
 * Input for the AI sprint-plan generator (POST /v1/plans).
 * Only `description` is required — every other field tunes the generated plan.
 * The AI will intelligently decide team_size, duration_weeks, and sprint_length_weeks
 * if they are not provided, using context from the description and any rules given.
 */
export interface IPlanGenerate {
  description: string;
  project_name?: string;
  project_id?: string;
  team_size?: number;
  team_breakdown?: ITeamBreakdown;
  duration_weeks?: number;
  sprint_length_weeks?: number;
  start_date?: string;
  deadline?: string;
  rules?: string;
  features?: string[];
  constraints?: string[];
  /**
   * When true, the service will compute team-size suggestions and embed them
   * in the generated plan's assumptions. Helpful when the user leaves team
   * fields empty and wants the AI to propose an optimal team configuration.
   */
  ask_team_suggestion?: boolean;
  /** Generated by the service when ask_team_suggestion is used. */
  team_suggestions?: ITeamSuggestion[];
  /**
   * Detailed task-level scope with assignee, estimated hours, and actual hours.
   * Used to inform the AI about the real workload and team capacity.
   */
  task_scope?: IPlanTaskScope[];
}

/** A single task with assignee, estimated hours, and actual/spent hours. */
export interface IPlanTaskScope {
  /** Human-readable task name or title. */
  task: string;
  /** Team member assigned to the task. */
  assignee: string;
  /** Estimated hours to complete the task. */
  estimate_hours: number;
  /** Actual hours spent or committed (can be larger than estimate). */
  actual_hours: number;
  /** Optional category/grouping for the task (e.g., "Payment", "Delivery"). */
  category?: string;
  /** Optional priority. */
  priority?: 'low' | 'medium' | 'high' | 'critical';
}

